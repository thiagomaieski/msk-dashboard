// Start r64-fixture-server.mjs first. R64_PLAYWRIGHT_MODULE points to an installed playwright-core.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.R64_PLAYWRIGHT_MODULE || 'playwright-core');
const browser = await chromium.launch({headless:true,channel:'chrome'});
const context = await browser.newContext({viewport:{width:1440,height:1000},timezoneId:'America/Sao_Paulo'});
const out = join(tmpdir(),'r64-validation'); await mkdir(out,{recursive:true});
const checks=[], errors=[], blocked=[];
await context.route('**/*',r=>{
  if(new URL(r.request().url()).origin==='http://127.0.0.1:5199') return r.continue();
  blocked.push(r.request().url()); return r.abort();
});
const page=await context.newPage(); page.setDefaultTimeout(7000);
page.on('pageerror',e=>errors.push(e.message));
const snapshot = name => page.screenshot({path:join(out,name+'.png')});
try {
  await page.goto('http://127.0.0.1:5199/r64-fixture.html');
  await page.getByText('Aporte Tesouro IPCA+ 2035',{exact:true}).waitFor({timeout:20000});
  const count=await page.evaluate(()=>window.r6Store.getState().data.pessoal.length);
  await page.getByText('Aporte Tesouro IPCA+ 2035',{exact:true}).click();
  assert.equal(await page.getByLabel('Descrição',{exact:true}).inputValue(),'Aporte Tesouro IPCA+ 2035');
  assert.equal(await page.getByLabel('Data',{exact:true}).inputValue(),'2026-11-06');
  assert.equal(await page.evaluate(()=>window.r6Store.getState().editingId.pessoal),'pes-desp-010');
  await snapshot('investment-dark');
  checks.push('investment prefilled with selected ID');
  await page.getByLabel('Descrição',{exact:true}).fill('Aporte R64 editado');
  await page.getByRole('dialog').locator('input').nth(1).fill('1750,00');
  await page.getByLabel('Descrição',{exact:true}).click();
  await page.getByRole('button',{name:'Salvar',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  const saved=await page.evaluate(()=>({writes:window.r64Writes,data:window.r6Store.getState().data.pessoal}));
  assert.equal(saved.data.length,count); assert.equal(saved.writes.length,1);
  assert.equal(saved.writes[0].operation,'update'); assert.ok(saved.writes[0].path.endsWith('/pes-desp-010'));
  assert.equal(saved.data.find(p=>p.id==='pes-desp-010').descricao,'Aporte R64 editado');
  assert.equal(saved.data.find(p=>p.id==='pes-desp-010').valor,1750);
  checks.push('UI save updates original once, preserves count, zero addDoc');
  await page.getByTitle('Novo Investimento',{exact:true}).click();
  assert.equal(await page.getByLabel('Descrição',{exact:true}).inputValue(),'');
  assert.equal(await page.evaluate(()=>window.r6Store.getState().editingId.pessoal),null);
  await page.keyboard.press('Escape'); await page.getByRole('dialog').waitFor({state:'hidden'});
  checks.push('new investment clears old ID; Escape closes');
  await page.getByRole('button',{name:'Usar tema claro',exact:true}).click();
  await page.getByText('Aporte R64 editado',{exact:true}).click();
  await snapshot('investment-light');
  await page.getByRole('button',{name:'Cancelar',exact:true}).click();
  checks.push('light theme and investment cancel');
  await page.clock.setFixedTime(new Date('2026-12-01T01:59:00Z'));
  for(const [type,css] of [['pessoalReceita','modal-finance-pf'],['pessoalDespesa','modal-finance-pf'],['pessoalInvestimento','modal-finance-pf'],['negocioReceita','modal-finance-pj'],['negocioDespesa','modal-finance-pj'],['parcela','modal-finance-pj']]) {
    await page.evaluate(type=>window.r6Store.getState().openModal(type),type);
    const dialog=page.getByRole('dialog');await dialog.waitFor();
    assert.ok((await dialog.getAttribute('class')).includes(css));
    assert.equal(await dialog.locator('input[type=date]').first().inputValue(),'2026-11-30');
    await page.waitForFunction(()=>document.querySelector('[role=dialog]')?.contains(document.activeElement));
    if(type==='negocioReceita') await snapshot('pj-receipt-light');
    await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
    checks.push(type+': correct modal style, UTC-3 date, focus, Escape');
  }
  await page.clock.setFixedTime(new Date('2026-11-13T15:00:00Z'));
  await page.getByRole('link',{name:'Finanças Negócio',exact:true}).click();
  await page.getByRole('heading',{name:'Finanças do Negócio',exact:true}).waitFor();
  assert.ok(page.url().endsWith('/financas-negocio'));
  await page.getByRole('button',{name:'Usar tema escuro',exact:true}).click();
  await snapshot('pj-dark');
  await page.getByRole('link',{name:'Finanças Pessoais',exact:true}).click();
  await page.getByRole('heading',{name:'Finanças Pessoais',exact:true}).waitFor();
  assert.ok(page.url().endsWith('/financas-pessoais'));
  checks.push('PJ/PF navigation and dark/light theme');
  for(const [link,collection] of [['Finanças Pessoais','pessoal'],['Finanças Negócio','negocio']]) {
    await page.getByRole('link',{name:link,exact:true}).click();
    await page.getByRole('heading',{name:collection==='negocio'?'Finanças do Negócio':link,exact:true}).waitFor();
    const downloadPromise=page.waitForEvent('download');
    await page.getByRole('button',{name:'Exportar CSV',exact:true}).click();
    const download=await downloadPromise; await download.saveAs(join(out,collection+'.csv'));
    assert.ok(download.suggestedFilename().endsWith('.csv'));
    await page.getByRole('button',{name:'Importar Dados',exact:true}).click();
    assert.equal(await page.evaluate(()=>window.r6Store.getState().editingId.importType),collection);
    await page.locator('input[type=file]').setInputFiles({name:'r64.csv',mimeType:'text/csv',buffer:Buffer.from('Data,Descrição,Valor\n2026-11-13,Receita R64 isolada,123.45')});
    await page.getByRole('button',{name:'Importar como Receitas',exact:true}).click();
    await page.getByRole('button',{name:'Importar 1 lançamentos',exact:true}).click();
    const call=await page.evaluate(()=>window.r6Calls.filter(c=>c.action==='bulkAddFinancas').at(-1));
    assert.ok(JSON.stringify(call.args).includes(collection));
    assert.ok(JSON.stringify(call.args).includes('Receita R64 isolada'));
    await page.evaluate(()=>window.r6Store.getState().closeModal());
    checks.push(collection+': CSV download and import dispatch with mock persistence');
  }
  const relation=await page.evaluate(()=>{
    const s=window.r6Store.getState(),client=s.data.clientes[0],project=s.data.projetos[0];
    const row={id:'r64-related',tipo:'Receita',descricao:'Receita relacionada R64',valor:500,data:'2026-11-13',entidade:client.nome,clienteId:client.id,projetoId:project.id,nf:'pendente',formaPagamento:'PIX'};
    window.r6Store.setState({realData:{...s.realData,negocio:[...s.realData.negocio,row]}});s._refreshData();s.openModal('negocioReceita',row.id);return row;
  });
  await page.getByLabel('Descrição',{exact:true}).fill('Receita relacionada editada R64');
  await page.getByRole('button',{name:/Salvar/,exact:false}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  const updated=await page.evaluate(()=>window.r6Store.getState().data.negocio.find(r=>r.id==='r64-related'));
  for(const key of ['id','entidade','clienteId','projetoId'])assert.equal(updated[key],relation[key]);
  checks.push('PJ receipt edit retains client name, client ID and project ID');
  await page.getByRole('link',{name:'Recorrência',exact:true}).click();
  const rec=await page.evaluate(()=>window.r6Store.getState().data.recorrencia.find(r=>r.periodicidade==='Mensal'));
  await page.evaluate(id=>window.r6Store.getState().openModal('pagarRecorrencia',id,{competencia:'2027-02'}),rec.id);
  await page.getByRole('dialog').waitFor(); await snapshot('recurrence-payment-dark');
  const before=await page.evaluate(()=>window.r64Writes.filter(w=>w.operation==='add').length);
  await page.getByRole('button',{name:'Registrar Pagamento',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  const payment=await page.evaluate(()=>window.r64Writes.filter(w=>w.operation==='add'));
  assert.equal(payment.length,before+1); assert.equal(payment.at(-1).payload.recorrenciaId,rec.id);
  assert.equal(payment.at(-1).payload.competencia,'2027-02');
  assert.equal(payment.at(-1).payload.clienteId,rec.clienteId||'');
  await page.evaluate(id=>window.r6Store.getState().openModal('pagarRecorrencia',id,{competencia:'2027-02'}),rec.id);
  assert.equal(await page.getByRole('button',{name:'Registrar Pagamento',exact:true}).isDisabled(),true);
  await page.keyboard.press('Escape');
  checks.push('recurrence payment creates one linked PJ revenue; second payment disabled');
  await page.evaluate(()=>{
    const s=window.r6Store.getState();
    window.r6Store.setState({realData:{...s.realData,recorrencia:[...s.realData.recorrencia,{id:'r64-undated',cliente:'Sem data fixture',valor:100,periodicidade:'Mensal',status:'Ativo'}]}});
    s._refreshData();
  });
  await page.getByRole('link',{name:'Dashboard',exact:true}).click();
  await page.locator('.dashboard-overview').waitFor();
  await snapshot('dashboard-dark');
  assert.ok((await page.locator('body').innerText()).includes('sem data no histórico'));
  checks.push('Dashboard renders corrected KPIs and explicit undated history label');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({checks,errors,blocked,out},null,2));
} finally {
  await writeFile(join(out,'browser-results.json'),JSON.stringify({checks,errors,blocked},null,2));
  await browser.close();
}
